import assert from 'node:assert/strict';
import {scalar,text,blank,date,day,number,matches,apiFilter,convert,equal} from './supabase/functions/_shared/engine.ts';
assert.equal(text('00123'),'00123');
assert.equal(scalar([{type:'text',text:'商品'}]),'商品');
assert.equal(blank(' \u3000'),true);
assert.equal(number('１,２３４.５０'),1234.5);
assert.throws(()=>number('抹茶玉米片30g'));
assert.equal(day('2026/10/14 23:59:59'),'2026-10-14');
assert.equal(day(46309),'2026-10-14');
assert.equal(date('2026-10-14 00:00:00'),date('2026-10-13T16:00:00Z'));
assert.throws(()=>date('2026-02-30'));
assert.equal(convert(123,{name:'编码',type:1,writable:true}),'123');
assert.equal(convert('00123',{name:'编码',type:1,writable:true}),'00123');
assert.throws(()=>convert('x',{name:'公式',type:20,writable:false}));
assert.equal(equal(null,''),true);
assert.equal(equal('00123','123'),false);
assert.equal(equal('00123',123,'number'),true);
const fs=[{id:'name',name:'货品名称',type:1},{id:'code',name:'货品编号',type:1},{id:'date',name:'发货时间',type:5}];
const cs=[{field:'name',op:'not_empty'},{field:'code',op:'empty'}];
assert.equal(matches({name:'商品',code:''},cs,'all',fs),true);
assert.equal(matches({name:'',code:''},cs,'all',fs),false);
assert.equal(matches({name:'',code:''},cs,'any',fs),true);
assert.equal(matches({date:'2026/10/14 23:59:59'},[{field:'date',op:'date_range',value:'2026-10-12',end:'2026-10-14'}],'all',fs),true);
assert.equal(apiFilter([...cs,{field:'date',op:'yesterday'}],'any',fs),null);
assert.equal(apiFilter(cs,'all',fs).conditions[0].field_name,'货品名称');
console.log('engine: 21 assertions passed');
